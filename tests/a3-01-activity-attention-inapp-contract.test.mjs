test('10 — copy authority: APPROVED / CANON byte-equal to the pinned registry; no FIXTURE as Product copy; one Copy Gate', () => {
  const registry = JSON.parse(read(REGISTRY));
  assert.equal(gitBlob(REGISTRY), 'feaee4405d07db30bf7689257c866a7442bce927', 'the pinned P4-C3 registry P4-C4 ratified');
  const rows = new Map(registry.rows.map((row) => [row.k, row]));
  const copy = read(`${ACTIVITY}/copy.ts`);
  const cited = [...copy.matchAll(/\/\/ (?:APPROVED|CANON) — ((?:p3\.)?[\w.*]+)/gu)].map((m) => m[1]);
  assert.ok(cited.length >= 30, 'the copy module cites its registry keys');
  for (const key of cited) {
    const expand = key.endsWith('.*') ? registry.rows.filter((row) => row.k.startsWith(key.slice(0, -1))) : [rows.get(key)];
    for (const row of expand) {
      assert.ok(row, `${key} is a registry key`);
      assert.ok(['CANON', 'PROPOSED_FOR_PO_REVIEW'].includes(row.st), `${row.k} is CANON or P4-C4-ratified`);
      assert.ok(copy.includes(row.ar), `${row.k} Arabic is byte-equal: ${row.ar}`);
      assert.ok(copy.includes(row.en.replace(/'/gu, "\\'")) || copy.includes(row.en), `${row.k} English is byte-equal: ${row.en}`);
    }
  }
  const fixtures = registry.rows.filter((row) => row.st === 'FIXTURE_ONLY' || row.st === 'AUDIT_OWNED').flatMap((row) => [row.ar, row.en]).filter((text) => text && text !== '—' && text.length > 6);
  const production = [...sourcesUnder(ACTIVITY), `${MOBILE}/settings/NotificationsSection.tsx`].map(read).join('\n');
  for (const text of fixtures) assert.equal(production.includes(text), false, `FIXTURE / AUDIT_OWNED text is not Product copy: ${text}`);
  assert.match(copy, /export const ACTIVITY_COPY_GATE = Object\.freeze\(\{\n {2}status: '(PROPOSED — AWAITING PRODUCT OWNER APPROVAL|APPROVED BY THE PRODUCT OWNER[^']*)'/u, 'the one Copy Gate states its status');
});

