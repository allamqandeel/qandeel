/**
 * A3-01 — Activity & Attention Core + In-App Production Integration: the static contract.
 *
 * It guards, against the repository as written (Task Contract §22 "Root contract"):
 *   1. I-08N-01 and P3 are CONSUMED, not rewritten: their records and the P3-A sources are byte-unchanged, and the two P3
 *      glyphs are generated from P3-A (`--check`), on P2's unchanged `sig.mjs`, through the P2 / VPORT-02 mechanism;
 *   2. no WebView, no P3-A proof runtime and no runtime icon package entered production;
 *   3. no native Push, device token, provider or OS notification code slipped into A3-01 (A3-02 owns it);
 *   4. Activity is not a World: the depth pair is still exactly Conversation ↔ Analysis, and no Global Switcher exists;
 *   5. no Activity entry, no strip and no call-safe strip in the Analysis; the entry is composed ONCE, at the START edge;
 *   6. no global raw count anywhere: the API's global indicator and the device's decoder are presence only;
 *   7. ONE Direct Entry contract, revalidated at open, typed future destinations failing closed;
 *   8. HIM / HSE "attention" is not the Activity store: nothing in A3-01 reads it;
 *   9. "Reduce" is no score, class rule or threshold, and the absent Proactive Gate fails closed;
 *  10. copy authority: every APPROVED / CANON string is byte-equal to the pinned P4-C3 registry; no FIXTURE sentence is
 *      Product copy; every unapproved row lives in the ONE Product Copy Gate;
 *  11. A3-02 is the named owner of native Push, and Stage 3 is not claimed closed;
 *  12. registration.
 */
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
