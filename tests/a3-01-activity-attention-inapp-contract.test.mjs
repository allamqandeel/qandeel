const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8').replace(/\r\n/gu, '\n');
const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/^\s*\/\/.*$/gmu, '').replace(/\s\/\/ .*$/gmu, '');
const code = (path) => stripComments(read(path));
const gitBlob = (path) => execFileSync('git', ['hash-object', new URL(path, root).pathname.replace(/^\/([A-Za-z]:)/u, '$1')], { encoding: 'utf8' }).trim();

function sourcesUnder(dir) {
  const out = [];
  const walk = (relative) => {
    for (const name of readdirSync(new URL(relative, root))) {
      const path = `${relative}/${name}`;
      if (statSync(new URL(path, root)).isDirectory()) {
        if (!['__tests__', '__fixtures__', '__validation__'].includes(name)) walk(path);
      } else if (/\.(ts|tsx)$/u.test(name) && !/\.spec\.ts$/u.test(name)) {
        out.push(path);
      }
    }
  };
  walk(dir);
  return out;
}

