test('1 — I-08N-01 and P3 are consumed, not rewritten; the two P3 glyphs are generated from P3-A on P2', () => {
  const i08n = read('docs/canonical-authority/final-product-experience/i-08n/QANDEEL_I-08N-01_FINAL_CLOSURE_PACKAGE.md');
  assert.match(i08n, /\*\*Status:\*\* `CLOSED \/ NOTIFICATION & PROACTIVE ATTENTION PRODUCT CONTRACT FROZEN`/u);
  const p3 = read('docs/qandeel-p3-notification-activity-final-realization-canonical-closure.md');
  assert.match(p3, /> \*\*Status: `P3 — CLOSED \/ FROZEN — NOTIFICATION & ACTIVITY FINAL PRODUCT REALIZATION`\*\*/u);
  const generated = spawnSync(process.execPath, [new URL('apps/mobile/scripts/generate-p3-production.mjs', root).pathname.replace(/^\/([A-Za-z]:)/u, '$1'), '--check'], { encoding: 'utf8' });
  assert.equal(generated.status, 0, `the P3 glyph geometry is current: ${generated.stderr}`);
  const module = read(`${MOBILE}/iconography/p3-production.generated.ts`);
  assert.match(module, /GENERATED by apps\/mobile\/scripts\/generate-p3-production\.mjs/u);
  assert.deepEqual([...module.matchAll(/^ {2}"(\w+)": \{/gmu)].map((m) => m[1]), ['ledger', 'link'], 'only Open Ledger and Open Link are ported');
  const generator = read('apps/mobile/scripts/generate-p3-production.mjs');
  assert.match(generator, /ACTIVITY_ACCEPTED !== 'ledger'/u);
  assert.match(generator, /INTRO_ACCEPTED !== 'link'/u);
  assert.match(generator, /sha\(P3_SIG\) !== sha\(P2_SIG\)/u, 'P3 applies P2 and does not extend it');
  assert.doesNotMatch(stripComments(generator), /P3G\.(bell|door)|WITHDRAWN\./u, 'comparison drawings are never executed');
  // The P3-A package is evidence: nothing in it is edited by A3-01. Pinned by content (every path and its bytes, as at
  // the baseline 34ea439), not by asking git, so the claim also holds in the forward-safety mirror, which is no repository.
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(new URL(dir, root), { withFileTypes: true })) {
      if (entry.isDirectory()) walk(`${dir}/${entry.name}`);
      else files.push(`${dir}/${entry.name}`);
    }
  };
  walk(P3A);
  const digest = createHash('sha256');
  for (const file of files.sort()) {
    digest.update(`${file.slice(P3A.length + 1)}\0`);
    digest.update(`${createHash('sha256').update(readFileSync(new URL(file, root))).digest('hex')}\n`);
  }
  assert.equal(files.length, 140, 'the P3-A package has exactly the files it had at the baseline');
  assert.equal(digest.digest('hex'), 'ef10ca6e1a949e6193f023f514f4e6dd3e03b9f664b408a3a84a685e8fa7eeee', 'the P3-A package bytes are untouched');
});

