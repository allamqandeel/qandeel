test('5 — no Activity entry or strip in the Analysis; the entry is composed once, at the START edge', () => {
  for (const file of [`${MOBILE}/conversation/AnalysisReturnBar.tsx`, `${MOBILE}/integration/composition/LivingAnalysisMap.tsx`]) {
    assert.doesNotMatch(code(file), /ActivityEntry|AttentionStrip|CallSafeStrip|qandeel-activity/u, `${file} carries no Activity entry or strip`);
  }
  const depth = code(`${MOBILE}/integration/composition/DepthComposition.tsx`);
  assert.equal((depth.match(/<ActivityEntry\b/gu) ?? []).length, 1, 'one entry');
  assert.match(depth, /chromeStart=\{onSignOut === undefined \? null : \(\n\s*<ActivityEntry /u, 'handed to the non-Analysis upper chrome');
  assert.match(depth, /strip !== null && strip\.form === 'ORDINARY' && depth === 'CONVERSATION'/u, 'the strip host never mounts at the Analysis depth');
  assert.match(depth, /activityShown && depth === 'CONVERSATION' && onSignOut !== undefined \?/u, 'Activity is never reached from the Analysis');
  const surface = read(`${MOBILE}/conversation/ConversationSurface.tsx`);
  const chrome = surface.slice(surface.indexOf('minHeight: insets.top + HEADER_MIN_HEIGHT'), surface.indexOf('onOpenSettings === undefined ? null'));
  assert.equal((chrome.match(/<Control\b/gu) ?? []).length, 1, 'the chrome still draws exactly one control of its own');
  assert.match(chrome, /chromeStart === null \? null : <View testID="qandeel-chrome-start">\{chromeStart\}<\/View>/u);
  assert.match(code(`${ACTIVITY}/presentation.ts`), /if \(context\.surface === 'ANALYSIS'\) return \{ kind: 'WAIT' \};/u, 'ordinary attention waits inside the Analysis');
  // The call-safe strip is built, not mounted: no call authority exists (QAN-BL-VOICE-01).
  for (const file of mobileProduction.filter((f) => !f.endsWith('CallSafeStrip.tsx'))) assert.doesNotMatch(code(file), /<CallSafeStrip\b/u, `${file} mounts no call-safe strip`);
  assert.match(code(`${ACTIVITY}/call-truth.ts`), /PRODUCTION_CALL_TRUTH: CallTruth = Object\.freeze\(\{ kind: 'NO_CALL_KNOWN' \}\)/u);
  assert.doesNotMatch(mobileProduction.filter((f) => !f.endsWith('call-truth.ts') && !f.endsWith('presentation.ts')).map(code).join('\n'), /kind: 'ACTIVE'/u, 'nothing in production fabricates an active call');
});

