function sourcesUnder(dir) {
  const found = [];
  for (const entry of readdirSync(new URL(dir, root))) {
    const path = `${dir}/${entry}`;
    if (statSync(new URL(path, root)).isDirectory()) {
      if (entry === '__tests__' || entry === '__fixtures__' || entry === '__validation__') continue;
      found.push(...sourcesUnder(path));
    } else if (/\.(?:ts|tsx)$/u.test(entry)) {
      found.push(path);
    }
  }
  return found;
}
const production = sourcesUnder(MOBILE);
const code = (path) => stripComments(read(path));

