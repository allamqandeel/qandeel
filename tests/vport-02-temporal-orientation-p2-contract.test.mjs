test('QAN-BL-A11Y-01: the T-10 camera and temporal motion read the ONE live Reduce Motion reader', () => {
  const owner = code(`${MOBILE}/motion/runtime/reduce-motion.ts`);
  assert.match(owner, /AccessibilityInfo\.addEventListener\('reduceMotionChanged'/u);
  // ONE platform listener in the whole app.
  const listeners = production.filter((path) => /addEventListener\('reduceMotionChanged'/u.test(code(path)));
  assert.deepEqual(listeners, [`${MOBILE}/motion/runtime/reduce-motion.ts`], 'one reader, one listener');
  for (const path of [`${MOBILE}/motion/presentation-camera/usePresentationCamera.ts`, `${MOBILE}/temporal-navigation/motion/useTemporalMotion.ts`]) {
    const text = code(path);
    assert.match(text, /const reducedMotion = useReduceMotion\(\);/u, `${path} reads the live reader`);
    assert.doesNotMatch(text, /useReducedMotion/u, `${path} no longer reads Reanimated's launch-only value`);
    // Every animation names its reduced-motion behaviour, so the live plan is the only authority.
    for (const match of text.matchAll(/with(?:Timing|Spring)\(/gu)) {
      const call = text.slice(match.index, match.index + 260);
      // The camera's travel shares one spring config, itself asserted to name Never just below.
      if (/^withSpring\(0, spring\)/u.test(call)) continue;
      const closes = call.indexOf('})');
      assert.match(call.slice(0, closes + 2), /reduceMotion: (?:ReduceMotion\.Never|NEVER)/u, `${path}: ${call.slice(0, 80)}… names ReduceMotion.Never`);
    }
  }
  assert.match(code(`${MOBILE}/motion/presentation-camera/usePresentationCamera.ts`), /const spring = \{ duration: plan\.translationMs, dampingRatio: plan\.dampingRatio, reduceMotion: ReduceMotion\.Never \};/u);
  const proof = read(`${MOBILE}/motion/__tests__/reduce-motion-mid-session.test.tsx`);
  assert.match(proof, /await act\(async \(\) => emit\(true\)\);[\s\S]*applyCanonicalChange\(LONG_TRAVEL\)\.kind\)\.toBe\('CUT_AND_RESOLVE'\)/u, 'proved mid-session, without a remount');
  assert.match(proof, /expect\(listening\)\.toBe\(1\);/u);
});

