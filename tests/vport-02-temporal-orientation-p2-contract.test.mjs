test('production draws the frozen P2 Temporal Spine C, generated from the merged P2-A package and current', () => {
  execFileSync(process.execPath, [join(rootPath, 'apps/mobile/scripts/generate-p2-production.mjs'), '--check'], { stdio: 'pipe' });
  const generated = read(GENERATED);
  assert.match(generated, /^\/\*\*\n \* GENERATED by apps\/mobile\/scripts\/generate-p2-production\.mjs — do not edit by hand\./u);
  for (const source of ['app.js', 'machines.mjs', 'sig.mjs']) {
    assert.match(generated, new RegExp(`${P2A.replace(/[.]/gu, '\\.')}/${source.replace(/[.]/gu, '\\.')}  [0-9a-f]{64}`, 'u'), `the generated geometry names ${source} and its hash`);
  }
  const generator = read('apps/mobile/scripts/generate-p2-production.mjs');
  // The accepted variants and nothing else: C for the Spine, A for the Rail, N1 for the glyphs.
  assert.match(generator, /if \(machines\.SPINE_RECOMMENDED !== 'C'\) fail/u);
  assert.match(generator, /if \(machines\.RAIL_RECOMMENDED !== 'A'\) fail/u);
  assert.match(generator, /if \(OPEN\.id !== 'N1'\) fail/u);
  assert.match(generator, /aperture\('C', /u, 'the proof\'s own aperture() is executed for variant C');
  assert.doesNotMatch(generator, /aperture\('[AB]'/u, 'no comparison variant is ever executed');
  // The temporal surface draws it: the spine, the two apertures on T-06's own markers, and the Live terminal.
  for (const used of ['<SpineLayer', '<Aperture kind="COMMITTED"', '<Aperture kind="PREVIEW"', '<LiveTerminal']) {
    assert.ok(layer.includes(used), `the production temporal surface renders ${used}`);
  }
  assert.match(layer, /from '\.\.\/\.\.\/iconography'/u);
  assert.match(machine, /P2_SPINE/u);
  // A preview has no committed mark; the committed aperture has one.
  assert.match(machine, /kind === 'COMMITTED' \? \(\s*<RoundedRect/u);
  // Not promoted into Product law: the craft values are labelled as such where they are emitted.
  assert.match(generated, /reference CRAFT values, not Product law/u);
});

