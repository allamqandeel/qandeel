const root = new URL('../', import.meta.url);
const rootPath = fileURLToPath(root);
const read = (path) => readFileSync(new URL(path, root), 'utf8').replace(/\r\n/gu, '\n');
const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/\/\/[^\n]*/gu, '');
const gitBlob = (path) => execFileSync('git', ['hash-object', path], { cwd: rootPath, encoding: 'utf8' }).trim();

const MOBILE = 'apps/mobile/src';
const ICONOGRAPHY = `${MOBILE}/iconography`;
const GENERATED = `${ICONOGRAPHY}/p2-production.generated.ts`;
