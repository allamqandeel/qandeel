test('no WebView, no HTML world, no runtime icon package', () => {
  const mapFiles = [];
  const walk = (dir) => {
    for (const entry of readdirSync(new URL(dir, root), { withFileTypes: true })) {
      if (entry.isDirectory()) walk(`${dir}/${entry.name}`);
      else if (/\.tsx?$/u.test(entry.name)) mapFiles.push(`${dir}/${entry.name}`);
    }
  };
  walk('apps/mobile/src/map');
  for (const file of mapFiles) {
    const code = stripComments(read(file));
    for (const forbidden of ['react-native-webview', 'WebView', '<iframe', 'srcdoc', 'hugeicons', 'react-native-svg']) {
      assert.equal(code.includes(forbidden), false, `${file} must not contain ${forbidden}`);
    }
    // The canonical prototype is named only as provenance in a generated module, never loaded.
    if (!file.endsWith('.generated.ts')) assert.equal(code.includes('wf-living-constellation'), false, `${file} must not load the prototype`);
  }
  const manifest = JSON.parse(read('apps/mobile/package.json'));
  for (const name of Object.keys({ ...manifest.dependencies, ...manifest.devDependencies })) {
    assert.equal(/webview|hugeicons|react-native-svg/iu.test(name), false, `${name} is not a VPORT-01 dependency`);
  }
});

