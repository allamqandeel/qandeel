/**
 * VPORT-01 — Living Analysis World — Final Production Visual Port. The static guards.
 *
 * The port replaced the T-04 neutral placeholder paint with the frozen I-08B1 world. These guards keep
 * it that way and keep it honest: the world's values come from the closed sources by a deterministic
 * generator; the Map paints no placeholder, no literal palette of its own, no WebView and no HTML; the
 * visual owner reads no analytical quantity and draws no relation without a fact; and nothing visual is
 * an input to scene membership, placement, hit testing or accessibility.
 */

const root = new URL('../', import.meta.url);
const rootPath = fileURLToPath(root);
const read = (path) => readFileSync(new URL(path, root), 'utf8').replace(/\r\n/gu, '\n');
const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/\/\/[^\n]*/gu, '');

const I08B1 = 'docs/design/canonical-artifacts/living-analysis/i-08b1/wf-living-constellation.html';
const I08B1_SHA256 = '4dfd9d27d752c3a445168c0cc7067d71df4ada84bc61b806d12c8bb3202bc413';
const VISUAL_DIR = 'apps/mobile/src/map/visual';
const GENERATED = ['world-visual.generated.ts', 'world-field.generated.ts'];
// LA-VIS-01 (controlled re-anchor): the declared presentation palette joins the hand-written owner, under every rule below.
// LA-VIS-01 (final closure re-anchor): the mass material `world-mass.ts` joins it too, under every rule below.
const HAND_WRITTEN = ['WorldMarks.tsx', 'WorldStrata.tsx', 'index.ts', 'useWorldResponse.ts', 'world-presentation.ts', 'world-resolver.ts', 'world-chroma.ts', 'world-mass.ts'];

const visual = Object.fromEntries([...GENERATED, ...HAND_WRITTEN].map((file) => [file, read(`${VISUAL_DIR}/${file}`)]));
const visualCode = Object.fromEntries(HAND_WRITTEN.map((file) => [file, stripComments(visual[file])]));
// S5-03B Phase 1 (controlled re-anchor, after the Personal golden equivalence proof): MapCanvas remains the Personal
// owner of the Map's paint and delegates, verbatim, to the generic world composition in WorldCanvas.tsx; MapSurface
// delegates its presentation mechanics to useWorldSurface.ts. The world's rules are asserted on the owner TOGETHER WITH
// the seam its code now lives in; none is weakened.
const personalCanvasOwner = stripComments(read('apps/mobile/src/map/renderer/MapCanvas.tsx'));
const worldCanvas = stripComments(read('apps/mobile/src/map/renderer/WorldCanvas.tsx'));
const canvas = `${personalCanvasOwner}\n${worldCanvas}`;
// S5-03B R1 (controlled re-anchor): the world's expression is gathered by the one Living Analysis world view
// (`useWorldView` in WorldViewSurface.tsx, called in place by MapSurface), so it is asserted there too.
const surface = stripComments(read('apps/mobile/src/map/renderer/MapSurface.tsx')) + '\n' + stripComments(read('apps/mobile/src/map/renderer/WorldViewSurface.tsx')) + '\n' + stripComments(read('apps/mobile/src/map/renderer/useWorldSurface.ts'));

test('the closed I-08B1 source is untouched, and the generated world is current and reproducible', () => {
  const sha = createHash('sha256').update(readFileSync(new URL(I08B1, root))).digest('hex');
  assert.equal(sha, I08B1_SHA256, 'the canonical I-08B1 source is read-only');
  // Re-running the generator against the frozen sources reproduces both modules byte for byte.
  execFileSync(process.execPath, [join(rootPath, 'apps/mobile/scripts/generate-world-visual.mjs'), '--check'], { stdio: 'pipe' });
  for (const file of GENERATED) {
    const text = visual[file];
    assert.match(text, /^\/\*\*\n \* GENERATED by apps\/mobile\/scripts\/generate-world-visual\.mjs — do not edit by hand\./u, `${file} declares its generator and the no-hand-edit rule`);
    assert.match(text, new RegExp(`${I08B1.replace(/[.]/gu, '\\.')}  ${I08B1_SHA256}`, 'u'), `${file} names the canonical source and its exact hash`);
  }
});

test('the generator takes the world from the canonical source itself, never from prose', () => {
  const generator = read('apps/mobile/scripts/generate-world-visual.mjs');
  // The four canonical painters are EXECUTED, unmodified, against a recording context.
  for (const declaration of ["block('function dustTile(){')", "block('function sprite(hue,sat,light,profile){')", "block('function shadeSprite(){')", "block('function nodePath(ctx,k,x,y,r,rot){')", "block('const P={')"]) {
    assert.ok(generator.includes(declaration), `the generator lifts ${declaration} from the canonical file`);
  }
  // The distance schedule is copied expression for expression, and its flags are the shipped ones.
  assert.match(generator, /const SCHEDULE_KEYS = \['lod', 'map', 'mapA', 'far', 'atmo', 'cosmos'/u);
  assert.match(generator, /for \(const flag of \['let HIER=true;', 'let LODON=true;', 'let MAPON=true;', 'let FARCAL=true;'\]\) exactLine\(flag\);/u);
  // Tokens through F2 FINAL's own resolver.
  assert.match(generator, /f2r\.loadTokens\(\{ appearance: 'dark', contrast \}\)/u);
  const generated = visual['world-visual.generated.ts'];
  const html = read(I08B1);
  for (const [, key, expression] of generated.matchAll(/^ {2}S\.(\w+) = (.+);$/gmu)) {
    assert.ok(new RegExp(`^\\s*S\\.${key}\\s*=\\s*${expression.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')};`, 'mu').test(html), `S.${key} is the canonical expression`);
  }
});

