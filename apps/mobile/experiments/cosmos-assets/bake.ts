// COSMOS asset bake (experimental). Runs at BUILD time in Node, never on a phone: writes the prepared atmosphere plates
// and the light atlas as image files from the deterministic generators in src/cosmos/core/atmosphere.ts.
// Usage: node bake.cjs <out-dir>   (bundle this file with esbuild first; needs @napi-rs/canvas)
import { ATMOSPHERES, bakeFibre, bakePlate, bakeSprite, plateStars, type PlateKind } from '../../src/cosmos/core/atmosphere';
import type { WorldKind } from '../../src/cosmos/core/stage';
declare const require: (m: string) => any; declare const process: any;
const { createCanvas, ImageData } = require('@napi-rs/canvas'); const fs = require('node:fs');
const out = process.argv[2]; const TILE = 1024;

function plate(world: WorldKind, kind: PlateKind, bake: number, size: number): Buffer {
  const small = createCanvas(bake, bake); small.getContext('2d').putImageData(new ImageData(bakePlate(world, kind, bake), bake, bake), 0, 0);
  const tile = createCanvas(size, size); const t = tile.getContext('2d'); t.imageSmoothingEnabled = true; t.imageSmoothingQuality = 'high';
  t.drawImage(small, 0, 0, size, size); t.globalCompositeOperation = 'lighter';
  const star = ATMOSPHERES[world].star; const k = size / TILE;
  for (const st of plateStars(world, kind)) for (const ox of [-1, 0, 1]) for (const oy of [-1, 0, 1]) {
    const x = (st.x + ox) * size; const y = (st.y + oy) * size; const R = st.r * 3.2 * k; if (x < -R || x > size + R || y < -R || y > size + R) continue;
    const g = t.createRadialGradient(x, y, 0, x, y, R); const c = `${Math.round(star[0] * (0.88 + st.warm * 0.12))},${Math.round(star[1] * 0.96)},${Math.round(star[2] * (1 - st.warm * 0.18))}`;
    g.addColorStop(0, `rgba(${c},${st.a})`); g.addColorStop(0.3, `rgba(${c},${st.a * 0.32})`); g.addColorStop(1, `rgba(${c},0)`); t.fillStyle = g; t.fillRect(x - R, y - R, R * 2, R * 2);
  }
  return tile.toBuffer('image/jpeg', 92);
}
const t0 = Date.now();
for (const world of ['PERSONAL', 'SHARED', 'PUBLIC'] as const) {
  fs.writeFileSync(`${out}/${world.toLowerCase()}-deep.jpg`, plate(world, 'DEEP', 512, 1024));
  fs.writeFileSync(`${out}/${world.toLowerCase()}-gas.jpg`, plate(world, 'GAS', 1024, 1024));
  fs.writeFileSync(`${out}/${world.toLowerCase()}-veil.jpg`, plate(world, 'VEIL', 256, 512));
}
// The light atlas: white with intensity in alpha; a host tints and turns each instance at draw time.
const FIBRE = 512; const SPRITE_PX = [160, 128, 128, 64, 48]; const PAD = 2;
const atlas = createCanvas(FIBRE * 3 + PAD * 4, FIBRE + 160 + PAD * 3); const a = atlas.getContext('2d');
const rects: number[][] = new Array(8);
let x = PAD;
SPRITE_PX.forEach((size, id) => { a.putImageData(new ImageData(bakeSprite(id, size), size, size), x, FIBRE + PAD * 2); rects[id] = [x, FIBRE + PAD * 2, size, size]; x += size + PAD; });
for (let v = 0; v < 3; v += 1) { const fx = PAD + v * (FIBRE + PAD); a.putImageData(new ImageData(bakeFibre(v, FIBRE), FIBRE, FIBRE), fx, PAD); rects[5 + v] = [fx, PAD, FIBRE, FIBRE]; }
fs.writeFileSync(`${out}/light-atlas.png`, atlas.toBuffer('image/png'));
fs.writeFileSync(`${out}/atlas.ts`, `// GENERATED by experiments/cosmos-assets/bake.ts. Do not edit.\n// [x, y, width, height] of each sprite in light-atlas.png, indexed by SPRITE in core/stage.ts.\nexport const ATLAS_SIZE = [${atlas.width}, ${atlas.height}] as const;\nexport const ATLAS_RECTS: ReadonlyArray<readonly [number, number, number, number]> = ${JSON.stringify(rects)};\n`);
console.log('baked in', ((Date.now() - t0) / 1000).toFixed(1), 's');
