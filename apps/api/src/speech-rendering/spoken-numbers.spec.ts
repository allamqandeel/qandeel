import { arabicCardinal, arabicNumberSpans } from './spoken-numbers';

/** S8B-04 CP1, contract v1.2 §6.3 A1 / SR-N1. */

const apply = (text: string): string => {
  let out = '';
  let cursor = 0;
  for (const s of arabicNumberSpans(text)) {
    out += text.slice(cursor, s.start) + s.spoken;
    cursor = s.end;
  }
  return out + text.slice(cursor);
};

describe('S8B-04 A1 spoken numbers', () => {
  it.each([
    [0, 'صفر'], [1, 'واحد'], [2, 'اثنين'], [11, 'أحد عشر'], [21, 'واحد وعشرين'], [100, 'مئة'], [250, 'مئتين وخمسين'],
    [1990, 'ألف وتسعمئة وتسعين'], [2000, 'ألفين'], [2500, 'ألفين وخمسمئة'], [3000, 'ثلاثة آلاف'], [1000000, 'مليون'],
  ])('cardinal %d → %s', (n, words) => {
    expect(arabicCardinal(n)).toBe(words);
  });

  it.each([
    ['الموعد في الساعة 7:30 مساءً.', 'الموعد في الساعة السابعة والنصف مساءً.'],
    ['ولد في 15/3/1990.', 'ولد في الخامس عشر من مارس عام ألف وتسعمئة وتسعين.'],
    ['ارتفع السعر بنسبة 25%.', 'ارتفع السعر بنسبة خمسة وعشرين في المئة.'],
    ['المسافة 3.5 كيلومتر.', 'المسافة ثلاثة كيلومترات ونصف.'],
    ['استنى 2 دقيقة.', 'استنى دقيقتين.'],
    ['بقي 1 يوم.', 'بقي يوم واحد.'],
    ['قعدت 3 ساعات.', 'قعدت ثلاث ساعات.'],
    ['دفعت 11 دولار.', 'دفعت أحد عشر دولار.'],
    ['الساعة 8:45.', 'الساعة التاسعة إلا ربعًا.'],
    ['بعد ٣ أيام.', 'بعد ثلاثة أيام.'],
  ])('%s → %s', (input, expected) => {
    expect(apply(input)).toBe(expected);
  });

  it.each([
    'عندي 7 أفكار.', 'جرب mp3 أو COVID-19.', 'النسخة 3.2.1 جاهزة.', 'رقمي 0123456789.', 'الساعة 25:99.',
    'تاريخ 32/13/2026 غلط.', 'GPT4 و x2.', 'العدد 12,000 كبير.',
  ])('leaves %s as written', (input) => {
    expect(apply(input)).toBe(input);
  });
});
