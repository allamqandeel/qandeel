/**
 * I-08B3.1-E1 — THE GENERATED DOCUMENTS.
 *
 * A results document must be generated from the artefacts. Not one figure below is typed:
 * every number is read out of data/*.json, which the suites wrote. A hand-entered number
 * can disagree with its own evidence, and nobody re-runs a suite on a document that
 * already says PASS.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = join(HERE, '..');
const rd = (p) => JSON.parse(readFileSync(join(PKG, p), 'utf8'));
const w = (p, s) => { writeFileSync(join(PKG, p), s); return p; };
const f4 = (n) => Number(n).toFixed(4);

export function docs() {
  const D = rd('data/E1_DERIVATION.json');
  const V = rd('data/E1_VALIDATION.json');
  const S = rd('data/E1_SKILLS.json');
  const B = existsSync(join(PKG, 'data/E1_BOARDS.json')) ? rd('data/E1_BOARDS.json') : { boards: [] };
  const F = existsSync(join(PKG, 'data/E1_FOCUS.json')) ? rd('data/E1_FOCUS.json') : { obligations: [], probes: [] };
  const VEN = rd('data/E1_VENDOR.json');
  const C = existsSync(join(PKG, 'data/E1_CONSISTENCY.json')) ? rd('data/E1_CONSISTENCY.json') : null;
  const out = [];

  /* ------------------------------------------------- E1_VALIDATION_RESULTS.md ------- */
  const layerName = { A: 'A — pure Node. Runs from a bare extraction with no project root, no siblings and no browser.', B: 'B — needs the rendered boards.', C: 'C — needs Chrome.' };
  out.push(w('docs/E1_VALIDATION_RESULTS.md', `# E1_VALIDATION_RESULTS

**I-08B3.1-E1.** Generated by \`tools/e1-docs.mjs\` from \`data/E1_VALIDATION.json\`,
\`data/E1_DERIVATION.json\`, \`data/E1_BOARDS.json\` and \`data/E1_FOCUS.json\`.
**Not one figure in this document is typed.**

## 1. Headline

| | |
|---|---|
| checks | **${V.summary.passed} / ${V.summary.checks}** |
| negative probes fired | **${V.summary.fired} / ${V.summary.probes}** |
| behavioural obligations | **${F.obligations.filter((o) => o.pass).length} / ${F.obligations.length}** |
| behavioural probes fired | **${F.probes.filter((p) => p.fired).length} / ${F.probes.length}** |
| dichromacy self-checks | **${D.selfCheck.filter((s) => s.pass).length} / ${D.selfCheck.length}** |
| boards rendered | **${B.boards.length}** |
| inherited artefacts vendored exact-byte | **${VEN.entries.length}** |
| Skill Gate | **${S.state}** |

Every check is paired with an input that must make it fail. A check proved only by the
thing it accepts is a sentence.

## 2. Layers

${['A', 'B', 'C'].map((l) => `**Layer ${layerName[l]}** ${V.checks.filter((c) => c.layer === l).length} checks.`).join('\n\n')}

## 3. The checks

| id | layer | check | result |
|---|---|---|---|
${V.checks.map((c) => `| ${c.id} | ${c.layer} | ${c.name} | ${c.pass ? '**PASS**' : '**FAIL**'} |`).join('\n')}

### Detail

${V.checks.map((c) => `**${c.id}** — ${c.detail}`).join('\n\n')}

## 4. The probes

${V.probes.map((p) => `**${p.id}** *${p.name}* — ${p.fired ? 'FIRED' : '**SILENT**'}. ${p.detail}`).join('\n\n')}

## 5. The behavioural proof

Real \`Input.dispatchKeyEvent\` Tab events through a real browser. A synthetic
\`KeyboardEvent\` constructed in page script carries no default action, so a Tab test
written in page JS measures its own \`focus()\` calls and always passes.

| obligation | result | detail |
|---|---|---|
${F.obligations.map((o) => `| ${o.name} | ${o.pass ? '**MET**' : '**FAILED**'} | ${o.detail} |`).join('\n')}

${F.probes.map((p) => `**probe — ${p.name}:** ${p.fired ? 'FIRED' : 'SILENT'}. ${p.detail}`).join('\n\n')}

## 6. The derived values

| | authored | quantised | recovered |
|---|---|---|---|
| **error ink** | \`oklch(${D.ERROR.authored.L} ${D.ERROR.authored.C} ${D.ERROR.authored.H})\` | \`${D.ERROR.hex}\` | L ${f4(D.ERROR.recovered.L)} C ${f4(D.ERROR.recovered.C)} H ${Number(D.ERROR.recovered.H).toFixed(2)} |
| **unavailable ink** | \`oklch(${D.DISABLED.authored.L} ${D.DISABLED.authored.C} ${D.DISABLED.authored.H})\` | \`${D.DISABLED.hex}\` | L ${f4(D.DISABLED.recovered.L)} C ${f4(D.DISABLED.recovered.C)} H ${Number(D.DISABLED.recovered.H).toFixed(2)} |

The derived FLOOR is **${D.FLOOR.toFixed(5)}** — the closest full OkLab distance Living Brass
keeps from the frozen reading ramp. The chromatic floor is **${D.CHROMATIC.toFixed(5)}** — Living
Brass's own chroma.

### Every floor, on the quantised error value

| floor | measured | required | |
|---|---|---|---|
${D.ERROR.floors.map((f) => `| ${f.name} | ${f.value.toFixed(5)} | ${f.floor} | ${f.pass ? 'pass' : '**FAIL**'}${f.value < f.floor * 1.05 ? ' · **BINDING**' : ''} |`).join('\n')}

**How much room remains.** ${D.ERROR.feasibleSamples} sampled points are feasible at this
hue, spanning L ${D.ERROR.feasibleL[0]}–${D.ERROR.feasibleL[1]} and C ${D.ERROR.feasibleC[0]}–${D.ERROR.feasibleC[1]};
the sRGB gamut edge is ${D.ERROR.gamutHeadroom} of chroma away. The hue moved
**${D.ERROR.hueDeviation}°** ${D.ERROR.hueDirection} from the sRGB red primary's
${f4(D.ERROR.hueAnchor)} — the minimum distance at which a value exists that keeps every
floor under ±1 least-significant bit per channel.

### The focus indicator pair

| against | indicator | companion | covered by |
|---|---|---|---|
${D.FOCUS.coverage.map((c) => `| ${c.against} \`${c.hex}\` | ${c.ring.toFixed(2)}:1 | ${c.companion.toFixed(2)}:1 | ${c.ringAlone ? 'the indicator' : '**the companion**'} |`).join('\n')}

Indicator alone: **${D.FOCUS.ringAloneCovers} / ${D.FOCUS.total}**. The pair: **${D.FOCUS.pairCovers} / ${D.FOCUS.total}**.

### The press response

| | |
|---|---|
| wash alpha | ${D.PRESS.alpha} (Material 3's pressed state-layer opacity — a production default) |
| derived floor it must clear | ${D.PRESS.derivedFloorStep.toFixed(5)} (the frozen World→Surface lightness step) |
| on the functional Surface | \`${D.FROZEN.SURFACE}\` → \`${D.PRESS.onSurface}\`, ΔL ${D.PRESS.dLSurface.toFixed(5)} |
| on the World | \`${D.FROZEN.WORLD}\` → \`${D.PRESS.onWorld}\`, ΔL ${D.PRESS.dLWorld.toFixed(5)} |
| collides with the one functional Surface value? | ${D.PRESS.collidesWithSurface ? '**YES**' : 'no'} |

## 7. Cross-artefact consistency

${C ? `\`tools/e1-consistency.mjs\` reads the **shipped artefacts back from disk** — ${C.filesScanned}
\`.md\` and \`.json\` files, with \`vendor/\` excluded because it is other packages' text and
must stay byte-identical. It does not read the source that wrote them and it does not read
rule text.

**A correction is not done until every generated surface agrees.** This guard earned its
place before it was finished: two surfaces — a token \`$description\` and a board caption —
were still carrying a claim E1 had already withdrawn when it was written.

| withdrawn claim | shipped anywhere? |
|---|---|
${C.forbidden.map((f) => `| ${f.label} | ${f.pass ? 'no' : '**' + f.hits.join(', ') + '**'} |`).join('\n')}

The exact strings the guard matches on are in \`tools/e1-consistency.mjs\` and in
\`data/E1_CONSISTENCY.json\`, which is the one file the guard does not scan — a report
about withdrawn claims has to be able to name them.

Each needle is also fed a sentence that MUST be caught, so the guard is proved in both
directions: **${C.probes.filter((p) => p.fired).length} / ${C.probes.length}** probes fired.

And every headline figure a document states is checked against the JSON that produced it:
**${C.counted.filter((x) => x.pass).length} / ${C.counted.length}** agree.

${C.counted.map((x) => `- \`${x.value}\` — ${x.what} — ${x.pass ? 'agrees in ' + x.where.length + ' document(s)' : '**MISSING FROM ' + x.missing.join(', ') + '**'}`).join('\n')}
` : '`data/E1_CONSISTENCY.json` absent — run `tools/e1-consistency.mjs`.'}

## 8. The boards

| id | file | what | size | distinct colours | chromatic px |
|---|---|---|---|---|---|
${B.boards.map((b) => `| ${b.id} | \`${b.file}\` | ${b.what} | ${b.width}×${b.height} | ${b.distinctColours} | ${b.chromatic} |`).join('\n')}

Every rendered board reports its own Arabic font fingerprint against a serif fallback, and
its own clipping-container overflow. A board that fell back to a system font, or that
squeezed its own content, fails the render rather than shipping.
`));

  /* ------------------------------------------------------- E1_SKILL_GATE.md --------- */
  out.push(w('docs/E1_SKILL_GATE.md', `# E1_SKILL_GATE

**I-08B3.1-E1.** Generated by \`tools/e1-docs.mjs\` from \`data/E1_SKILLS.json\`, which
\`tools/e1-skills.mjs\` wrote by walking the executing host and hashing every \`SKILL.md\`
it found.

**RESULT: ${S.state}.** ${S.inventoried} skill files inventoried and hashed.

A gate that lists what was *available* proves nothing. Every row below names the principle
actually read and a decision in E1 that would have been different without it. A row whose
consequence could be deleted without changing anything in the package does not belong here.

## USED

${S.used.map((u) => `### ${u.name}

- **path** \`${u.path}\`
- **bytes** ${u.bytes} · **sha256** \`${u.sha256}\`
- **read** — ${u.read}
- **consequence in E1** — ${u.consequence}
`).join('\n')}

## Available and deliberately not used

${S.notUsedAndWhy.map(([n, why]) => `- **${n}** — ${why}`).join('\n')}

## The third state

\`${S.probe.result}\`

The recorded skills live on the executing host and shipping them would redistribute
someone else's files, so a re-run on another machine cannot verify these digests. That
branch returns **UNVERIFIABLE** rather than PASS or FAIL, and a probe feeds it a synthetic
empty inventory on every run so the state is demonstrated even on the host where it never
fires. Carried forward from I-08B3.1-D2R.

## Full inventory

${S.inventory.length} files. \`sha256\` · bytes · path.

${S.inventory.map((i) => `- \`${i.sha256.slice(0, 16)}\` · ${String(i.bytes).padStart(6)} · \`${i.path}\``).join('\n')}
`));

  /* --------------------------------------------------------- E1_MANIFEST.md --------- */
  const files = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === '.build' || e.name.endsWith('.zip')) continue;
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else files.push(p);
    }
  };
  walk(PKG);
  const rows = files.map((p) => ({
    path: relative(PKG, p).replace(/\\/g, '/'),
    bytes: statSync(p).size,
    sha256: createHash('sha256').update(readFileSync(p)).digest('hex'),
  })).sort((a, b) => a.path.localeCompare(b.path));
  const total = rows.reduce((s, r) => s + r.bytes, 0);

  writeFileSync(join(PKG, 'data/E1_MANIFEST.json'), JSON.stringify({
    generatedBy: 'tools/e1-docs.mjs',
    note: 'A MANIFEST CANNOT STATE ITS OWN HASH. This file and E1_MANIFEST.md are written by the same run and are therefore absent from the list below; the archive digest in the execution report covers them both.',
    entries: rows.filter((r) => r.path !== 'data/E1_MANIFEST.json' && r.path !== 'docs/E1_MANIFEST.md'),
    totals: { files: rows.length, bytes: total },
  }, null, 2) + '\n');

  out.push(w('docs/E1_MANIFEST.md', `# E1_MANIFEST

**I-08B3.1-E1.** Generated by \`tools/e1-docs.mjs\`.

${rows.length} files, ${total.toLocaleString('en-US')} bytes.

**A manifest cannot state its own hash.** \`data/E1_MANIFEST.json\` and this document are
written by the same run, so they are listed here without digests rather than carrying the
previous generation's. The archive SHA-256 in the execution report covers both.

## Inherited, vendored exact-byte

Every file below was copied from a sealed predecessor package and re-hashed on both sides.
Check **R16** re-verifies them against those packages rather than trusting a directory name.

| published | source | bytes | sha256 |
|---|---|---|---|
${VEN.entries.map((e) => `| \`${e.published}\` | \`${e.source}\` | ${e.bytes} | \`${e.sha256.slice(0, 32)}…\` |`).join('\n')}

## Everything in the package

| path | bytes | sha256 |
|---|---|---|
${rows.map((r) => (r.path === 'data/E1_MANIFEST.json' || r.path === 'docs/E1_MANIFEST.md')
      ? `| \`${r.path}\` | — | *written by this run* |`
      : `| \`${r.path}\` | ${r.bytes} | \`${r.sha256.slice(0, 32)}…\` |`).join('\n')}
`));

  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const p of docs()) console.log('generated', p);
  console.log('generated data/E1_MANIFEST.json');
}
