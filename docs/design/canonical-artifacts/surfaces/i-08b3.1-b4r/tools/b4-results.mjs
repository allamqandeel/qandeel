for (const c of card.clean) P(`| \`${c.key}\` | ${c.elements} | ${c.failed.length ? 'FAIL — ' + c.failed.join(', ') : 'clean on all five rules'} |`);
P('');
P('### Violating fixtures — the SEALED predecessor\'s own cardification failure captures');
P('');
P('| fixture | what it is | expected to fire | actually fired | result |');
P('|---|---|---|---|---|');
for (const v of card.violating) {
  P(`| \`${v.key}\` | ${v.why} | ${v.expect.join(', ')} | ${v.fired.join(', ') || '**NOTHING**'} | ${yn(!v.missed.length)} |`);
}
P('');

/* -------------------------------------------------------------- B4.12 ---------------- */
P('## 4. B4.12 — Final integration check');
P('');
P('Each accepted composition is rendered **twice** through the sealed I-08B3.1-B3R product');
P('stylesheet: once with the custom properties the accepted package used, once with every canonical');
P('property **resolved from `tokens/qandeel-surface.tokens.json`**, each Product role taking its own');
P('value through its own alias chain. If a role alias pointed anywhere unintended, that role would');
P('change colour and the comparison would fail.');
P('');
P('**Custom properties supplied by the token file:**');
