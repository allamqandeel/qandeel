P('| property | resolved value |');
P('|---|---|');
for (const [k, v] of Object.entries(integ.tokenVars)) P(`| \`${k}\` | \`${v}\` |`);
P('');
P('**Deliberately NOT supplied** — deferred to I-08B3.1-E/F, kept at their B3 diagnostic values in');
P('*both* variants, which is `B4_PROOF_TO_PRODUCTION_MAP.md` in executable form:');
