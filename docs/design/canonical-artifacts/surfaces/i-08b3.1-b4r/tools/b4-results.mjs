P(`| Surface \`#181818\` remains stable | **YES** — the PASSAGE fill measures \`${s.passageFill.hex}\`, unchanged |`);
P('| no role-specific Surface change is needed | **YES** — one tone throughout; INV-01 and the N2 composition both hold |');
