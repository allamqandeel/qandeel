/**
 * I-08B3.1-B4 - writes `docs/B4_VALIDATION_RESULTS.md` from the artefacts the suites produced.
 *
 * Not one figure in that document is typed by hand. Every number is read back out of
 * `.i08b31-b4-work/*.json`, which is written by the tool that measured it. A results document with
 * hand-entered numbers is a document that can disagree with its own evidence, and the disagreement
 * is invisible until somebody re-runs the suite - which is the one thing nobody does to a document
 * that already says PASS.
 *
 * Writes its own file. Never `node b4-results.mjs > out`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { PKG, WORK } from './b4-tokens.mjs';

const need = (name) => {
  const p = join(WORK, name);
  if (!existsSync(p)) {
    throw new Error(`b4-results: ${name} is missing. Run the suite that produces it before ` +
      'generating results - this file reports measurements, it does not make them.');
  }
  return JSON.parse(readFileSync(p, 'utf8'));
};

const val = need('validation.json');
const inv = need('invariants.json');
const card = need('cardguard.json');
const integ = need('integration.json');
const sch = need('schema.json');

const L = [];
const P = (s = '') => L.push(s);
const yn = (b) => (b ? 'PASS' : 'FAIL');

P('# B4_VALIDATION_RESULTS');
P('');
P('**I-08B3.1-B4.** Machine-generated by `tools/b4-results.mjs` from the artefacts each suite wrote.');
P('No figure below is hand-entered.');
P('');

/* ------------------------------------------------------------------ summary ----------- */
const invFail = inv.invariants.filter((r) => !r.pass);
const invProbeFail = inv.probes.filter((p) => !p.hitTarget || p.unexpected.length);
const valFail = val.checks.filter((r) => !r.pass);
const valProbeFail = val.probes.filter((p) => !p.hit);
const cardCleanFail = card.clean.filter((c) => c.failed.length);
const cardProbeFail = card.violating.filter((v) => v.missed.length);
const integDiff = integ.cases.filter((c) => !c.identical);
const scrimMiss = integ.scrimRows.filter((r) => !r.match);
const schFail = sch.checks.filter((r) => !r.pass);
const schProbeFail = sch.probes.filter((p) => !p.hit);

P('## 0. Summary');
P('');
P('| suite | result |');
P('|---|---|');
P(`| **OFFICIAL DTCG 2025.10 schema validation** (I-08B3.1-B4R) | **${sch.checks.length - schFail.length}/${sch.checks.length}** checks pass, **${sch.probes.length - schProbeFail.length}/${sch.probes.length}** probes behaved as designed |`);
P(`| B4.9 token validation (custom QANDEEL) | **${val.checks.length - valFail.length}/${val.checks.length}** checks pass, **${val.probes.length - valProbeFail.length}/${val.probes.length}** probes rejected |`);
P(`| B4.5 production invariants | **${inv.invariants.length - invFail.length}/${inv.invariants.length}** pass, **${inv.probes.length - invProbeFail.length}/${inv.probes.length}** probes rejected as designed |`);
P(`| B4.8 anti-cardification guard | **${card.clean.length - cardCleanFail.length}/${card.clean.length}** clean compositions pass all ${card.rules.length} rules, **${card.violating.length - cardProbeFail.length}/${card.violating.length}** violating fixtures rejected |`);
P(`| B4.12 integration | **${integ.cases.length - integDiff.length}/${integ.cases.length}** compositions byte-identical, **${integ.cases.reduce((n, c) => n + c.pixelsDiffering, 0)}** pixels differ in total |`);
P(`| B4.4 scrim verification | **${integ.scrimRows.length - scrimMiss.length}/${integ.scrimRows.length}** measurements match predictions computed before the render |`);
P(`| invariants with no dedicated probe | ${inv.uncovered.length ? inv.uncovered.join(', ') : '**none**'} |`);
P('');

/* ------------------------------------------- B4R: the official schema, stated apart ---- */
P('## 0a. OFFICIAL DTCG 2025.10 SCHEMA VALIDATION — I-08B3.1-B4R');
P('');
P('Kept **separate from QANDEEL\'s own validation** on purpose. B4 validated its resolver document');
P('with a checker B4 wrote, against a shape B4 believed; both agreed and both were wrong. A validator');
P('authored beside the artefact cannot discover that its model of the standard is mistaken.');
P('');
P(`**Authority:** \`${sch.authority.officialBase}\`, vendored from \`${sch.authority.repository}\`,`);
P(`${sch.authority.files} schema files, dialect ${sch.authority.dialect}. Report pinned to publication`);
P(`commit \`${sch.authority.publicationCommit}\`; schema sources at \`${sch.authority.schemaSourceCommit}\`.`);
P(`Retrieved ${sch.authority.retrieved}. **Validator: \`${sch.authority.validator}\`** — third party, not authored here.`);
P('');
P('| check | result | detail |');
P('|---|---|---|');
for (const c of sch.checks) P(`| **${c.id}** ${c.title} | ${yn(c.pass)} | ${c.detail} |`);
P('');
P('### Negative probes — run through BOTH validators');
P('');
P('| probe | official schema | custom V-11 | result |');
P('|---|---|---|---|');
for (const p of sch.probes) {
  P(`| \`${p.id}\` ${p.label} | ${p.got.schema} *(expected ${p.expected.schema}, ${p.schemaErrors} err)* | ` +
    `${p.got.custom} *(expected ${p.expected.custom}, ${p.customErrors} err)* | ${yn(p.hit)} |`);
}
P('');
const partitioned = sch.probes.filter((p) => p.expected.schema === 'ACCEPT' && p.expected.custom === 'REJECT');
P(`**The two validators partition the specification; they do not duplicate it.** ${partitioned.length} of`);
P(`the ${sch.probes.length} probes are **accepted by the official schema and rejected only by V-11**`);
P(`(${partitioned.map((p) => '`' + p.id + '`').join(', ')}) — an undeclared \`$ref\` is a well-formed URI`);
P('reference, and a `default` naming a missing context is a plain string. The official schema carries a');
P('`$comment` saying exactly this must be checked at runtime. **A package that had replaced its own');
P('validator with schema validation, believing the schema strictly better, would have shipped both');
P(`defects with a clean report.** Probes caught by **neither** validator: **${sch.probes.filter((p) => p.escaped).length}**.`);
P('');

/* --------------------------------------------------------------- B4.9 ---------------- */
P('## 1. B4.9 — Token validation (custom QANDEEL rules)');
P('');
P(`Document under test: \`tokens/qandeel-surface.tokens.json\`, **${inv.tokens} tokens**, ` +
  `**${inv.conformanceErrors.length}** conformance errors.`);
