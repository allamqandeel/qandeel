P('| probe | aims at | rejected by | result |');
P('|---|---|---|---|');
for (const p of val.probes) {
  P(`| \`${p.id}\` ${p.why.split('.')[0]} | ${p.target} | ${p.rejectedBy.join(', ') || '**NOTHING**'} | ${yn(p.hit)} |`);
}
P('');

/* --------------------------------------------------------------- B4.5 ---------------- */
P('## 2. B4.5 — Production invariants');
P('');
P('| invariant | result | detail |');
