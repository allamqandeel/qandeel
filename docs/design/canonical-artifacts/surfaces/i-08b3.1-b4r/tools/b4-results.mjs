P('');
P('**What each probe is:**');
P('');
for (const p of inv.probes) P(`- \`${p.id}\` → ${p.target} — ${p.why}`);
P('');

/* --------------------------------------------------------------- B4.8 ---------------- */
P('## 3. B4.8 — Anti-cardification guard');
P('');
P('| rule | covers |');
P('|---|---|');
