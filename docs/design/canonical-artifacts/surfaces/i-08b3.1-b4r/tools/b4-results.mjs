for (const r of inv.invariants) P(`| **${r.id}** ${r.title} | ${yn(r.pass)} | ${r.detail} |`);
P('');
P('### Negative probes');
P('');
P('Collateral is listed because these rules overlap deliberately. An **unexpected** rejection would');
P('be a finding about the rules; there are none.');
P('');
