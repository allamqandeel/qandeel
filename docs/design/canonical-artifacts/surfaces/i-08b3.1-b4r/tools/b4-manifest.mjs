/**
 * I-08B3.1-B4 - the manifest, which RECONCILES rather than lists.
 *
 * A manifest that lists what is in a folder proves the folder exists. This one asks a harder
 * question of every shipped file: **which tool claims to have produced it, and does that claim hold
 * up?** A raster nobody claims is either an orphan from an earlier run or evidence of a step that
 * was not recorded, and both are worth a line in a report. B3R's manifest flagged three screenshots
 * on exactly this rule, and the fix there was to give the suite an artefact record - not to widen
 * the exemption.
 *
 * Writes its own file.
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { PKG, WORK } from './b4-tokens.mjs';

const sha = (b) => createHash('sha256').update(b).digest('hex').toUpperCase();

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(PKG).map((p) => {
  const buf = readFileSync(p);
  return { path: p, rel: relative(PKG, p).replace(/\\/g, '/'), bytes: buf.length, sha256: sha(buf) };
}).sort((a, b) => a.rel.localeCompare(b.rel));

/** Who claims what. A file matching no claim is reported, never quietly accepted. */
const CLAIMS = [
  { tool: 'tools/b4-tokens.mjs', test: (r) => r.startsWith('tokens/') },
  { tool: 'tools/b4-integration.mjs', test: (r) => r.startsWith('review/integration/') },
  { tool: 'tools/b4-skills.mjs', test: (r) => r === 'docs/B4_SKILL_INVENTORY.md' },
  { tool: 'tools/b4-results.mjs', test: (r) => r === 'docs/B4_VALIDATION_RESULTS.md' },
  { tool: 'tools/b4-results.mjs', test: (r) => r === 'docs/B4R_SCHEMA_CONFORMANCE.md' },
  { tool: 'tools/b4-manifest.mjs', test: (r) => r === 'docs/B4_MANIFEST.md' },
  /**
   * The vendored official schemas are NOT produced by this package and must never be claimed as
   * though they were. They are authored by the DTCG, retrieved with provenance, and checked by S-01
   * against `PROVENANCE.json` before any validation runs.
   */
  { tool: 'VENDORED — DTCG, see schemas/2025.10/PROVENANCE.json', test: (r) => r.startsWith('schemas/') },
  { tool: 'authored', test: (r) => r.startsWith('docs/') && r.endsWith('.md') },
  { tool: 'authored', test: (r) => r.startsWith('tools/') },
];
const claim = (rel) => (CLAIMS.find((c) => c.test(rel)) || { tool: null }).tool;

/* The artefact records each suite wrote, so a raster can be reconciled against the run that made it. */
const integ = existsSync(join(WORK, 'integration.json'))
  ? JSON.parse(readFileSync(join(WORK, 'integration.json'), 'utf8')) : null;
const recorded = new Set();
if (integ) for (const c of integ.cases) for (const f of c.files) recorded.add(f);

const rows = files.map((f) => {
  const by = claim(f.rel);
  const isRaster = /\.png$/i.test(f.rel);
  const inRecord = !isRaster ? null : recorded.has(f.rel);
  return { ...f, by, inRecord };
});

const unclaimed = rows.filter((r) => !r.by);
const orphanRasters = rows.filter((r) => r.inRecord === false);

const L = [];
const P = (s = '') => L.push(s);

P('# B4_MANIFEST (machine-generated)');
P('');
P('Generated by `tools/b4-manifest.mjs`. Every file in the package, hashed, with the tool that');
P('claims to have produced it. Rasters are additionally reconciled against the artefact record the');
P('suite that rendered them wrote, so a PNG nobody claims is reported rather than counted.');
P('');
const SELF = 'docs/B4_MANIFEST.md';
const others = rows.filter((r) => r.rel !== SELF);
P(`**${rows.length} files.** ${others.reduce((n, r) => n + r.bytes, 0).toLocaleString('en-US')} bytes ` +
  'excluding this manifest, whose own size and hash are settled only once it has been written.');
P('');
P(`Unclaimed files: **${unclaimed.length}**${unclaimed.length ? ' — ' + unclaimed.map((r) => '`' + r.rel + '`').join(', ') : ''}.`);
P(`Rasters not in any artefact record: **${orphanRasters.length}**${orphanRasters.length ? ' — ' + orphanRasters.map((r) => '`' + r.rel + '`').join(', ') : ''}.`);
P('');

const groups = [
  ['docs', (r) => r.rel.startsWith('docs/')],
  ['tokens', (r) => r.rel.startsWith('tokens/')],
  ['schemas (vendored, not authored here)', (r) => r.rel.startsWith('schemas/')],
  ['tools', (r) => r.rel.startsWith('tools/')],
  ['review', (r) => r.rel.startsWith('review/')],
  ['other', (r) => !/^(docs|tokens|schemas|tools|review)\//.test(r.rel)],
];

for (const [name, test] of groups) {
  const g = rows.filter(test);
  if (!g.length) continue;
  P(`## ${name} — ${g.length} file(s), ` +
    `${g.filter((r) => r.rel !== SELF).reduce((n, r) => n + r.bytes, 0).toLocaleString('en-US')} bytes`);
  P('');
  P('| file | bytes | produced by | in record | SHA-256 |');
  P('|---|---|---|---|---|');
  for (const r of g) {
    /**
     * A file cannot contain its own hash. Printing the hash of the PREVIOUS generation of this
     * manifest would be a wrong number that looks exactly like a right one, so it is named instead.
     * Its bytes are still listed, and the packager hashes it like every other entry.
     */
    const self = r.rel === 'docs/B4_MANIFEST.md';
    P(`| \`${r.rel}\` | ${self ? '—' : r.bytes.toLocaleString('en-US')} | ${r.by || '**UNCLAIMED**'} | ` +
      `${r.inRecord === null ? '—' : r.inRecord ? 'yes' : '**NO**'} | ` +
      `${self ? '*(this file — a manifest cannot state its own hash)*' : '`' + r.sha256 + '`'} |`);
  }
  P('');
}

P('## Provenance of values');
P('');
P('Not one canonical colour is typed in this package. `tools/b4-tokens.mjs` imports `WORLD`,');
P('`PRIMARY`, `SECONDARY`, `TERTIARY`, `SURFACE` and `SCRIM_BASELINE` from the sealed');
P('`I-08B3.1-B3R-OVERLAY-SEMANTICS-FOCUS-LIFECYCLE-VERIFICATION` package on disk, and');
P('`tools/b4-integration.mjs` renders through that package\'s own product stylesheet. B4 writes');
P('nothing into any predecessor, including its work directory.');
P('');
P('## The vendored schemas');
P('');
P('`schemas/2025.10/**` is **not this package\'s work**. It is the official DTCG 2025.10 JSON Schema');
P('set, retrieved from the specification\'s own repository and pinned because `designtokens.org` is');
P('unreachable from this environment. Every file carries its SHA-256 **and its git blob SHA-1**, the');
P('latter recomputed locally and matched against the blob sha the GitHub tree API reports for the');
P('official repository. `tools/b4r-schema.mjs` re-checks all of it (S-01) before validating anything,');
P('because a vendored authority that can be edited is not an authority.');
P('');
P('## Packaging');
P('');
P('`tools/b4r-package.ps1` builds the archive, re-hashes every predecessor archive — **including');
P('I-08B3.1-B4, which this package corrects and must leave untouched** — and refuses to write if any');
P('has moved. It then runs content guards against the shipped documents and token files.');
P('');

writeFileSync(join(PKG, 'docs', 'B4_MANIFEST.md'), L.join('\n') + '\n', { encoding: 'utf8' });
console.log(`wrote docs/B4_MANIFEST.md - ${rows.length} files`);
console.log(`  unclaimed: ${unclaimed.length}`);
console.log(`  rasters not in any artefact record: ${orphanRasters.length}`);
if (unclaimed.length || orphanRasters.length) process.exit(1);
