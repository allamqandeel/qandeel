function widthOf(str, s) {
  let w = 0;
  for (const ch of String(str).toUpperCase()) {
    const rows = F[ch] || F[' '];
    w += (rows[0].length + 1) * s;
  }
  return w - s;
}

function text(C, x, y, str, r, g, b, s) {
  s = s || 2;
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const rows = F[ch] || F[' '];
    const w = rows[0].length;
    for (let ry = 0; ry < 5; ry++) for (let rx = 0; rx < w; rx++) {
      if (rows[ry][rx] === '1') C.fill(cx + rx * s, y + ry * s, cx + rx * s + s - 1, y + ry * s + s - 1, r, g, b);
    }
    cx += (w + 1) * s;
  }
  return cx;
}

