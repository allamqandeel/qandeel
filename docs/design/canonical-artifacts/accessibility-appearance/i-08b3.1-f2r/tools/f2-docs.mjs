/**
 * I-08B3.1-F2 — THE GENERATED DOCUMENTS AND THE MANIFEST.
 *
 * Four documents are GENERATED rather than authored, because their whole content is a record of
 * what a tool measured: the skill gate, the reference gate, the validation results and the
 * manifest. An authored copy of any of them is a second source of truth that drifts, and
 * tools/f2-consistency.mjs exists because this project has watched that happen.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = join(HERE, '..');
const read = (rel) => JSON.parse(readFileSync(join(PKG, rel), 'utf8'));

function skillGate() {
  const g = read('data/F2_SKILLS.json');
  const used = g.rows.filter((r) => r.status === 'USED');
  const inspected = g.rows.filter((r) => r.status === 'INSPECTED — NOT APPLICABLE');
  const absent = g.rows.filter((r) => r.status === 'NOT AVAILABLE');
  return `# I-08B3.1-F2 — SKILL GATE

**Generated by \`tools/f2-skills.mjs\`. Do not edit — edit the tool.**

**State: ${g.state}** · ${g.inventoried} skill files inventoried on the executing host, each with its
exact path, byte length and sha256.

A gate that lists what was available proves nothing. Every skill named below carries one status and,
for USED, a CONCRETE CONSEQUENCE — a decision in F2 that would have been different without it. **A
row whose consequence could be deleted without changing anything in the package does not belong
under USED, and a skill dismissed from its name has not been inspected.**

**P-STATE.** The recorded skills live on the executing host and shipping them would redistribute
someone else's files, so a re-run on another machine returns \`${g.probe.result}\` rather than PASS
or FAIL. The probe feeds that branch a synthetic empty inventory on every run.

## USED — ${used.length}

${used.map((u) => `### ${u.name}

\`${u.path ?? 'NOT FOUND'}\`
${u.bytes ? `${u.bytes} B · sha256 \`${u.sha256}\`` : ''}

**What was read.** ${u.read}

**Consequence.** ${u.consequence}
`).join('\n')}

## INSPECTED — NOT APPLICABLE — ${inspected.length}

${inspected.map((i) => `- **${i.name}** — ${i.why}${i.copies.length ? `\n  ${i.copies.map((c) => `\`${c.sha256.slice(0, 12)}\` ${c.bytes} B`).join(' · ')}` : ''}`).join('\n')}

## NOT AVAILABLE — ${absent.length}

${absent.map((a) => `- **${a.name}** — ${a.why}`).join('\n')}

## Inventory

${g.inventory.map((i) => `- \`${i.sha256.slice(0, 12)}\` ${String(i.bytes).padStart(7)} B — \`${i.path}\``).join('\n')}
`;
}

function referenceGate() {
  const g = read('data/F2_REFERENCES.json');
  return `# I-08B3.1-F2 — REFERENCE GATE

**Generated by \`tools/f2-references.mjs\`. Do not edit — edit the tool.**

**State: ${g.state}** · ${g.count} references, **${g.changedSomething} of which changed a decision.**

${g.note}

Every row records four things, because a reference that only says WHAT IT SAYS is a citation rather
than a gate. **A row with nothing under WHAT IT CHANGED is honest and stays** — most references
confirm rather than redirect, and a gate that only listed the ones that redirected would imply that
everything was read for a reason it found afterwards.

${g.rows.map((r) => `---

## ${r.id} — ${r.source}

<${r.url}>
*${r.read}*

**WHAT IT SAYS**

${r.says.map((s) => `> ${s}`).join('\n>\n')}

**WHAT IT CHANGED.** ${r.changed}

**WHAT IT DID NOT CHANGE.** ${r.didNotChange}

**WHAT F2 DID DIFFERENTLY.** ${r.didDifferently}
`).join('\n')}`;
}

function validationResults() {
  const v = read('data/F2_VALIDATION.json');
  return `# I-08B3.1-F2 — VALIDATION RESULTS

**Generated by \`tools/f2-verify.mjs\`. Do not edit — edit the tool.**

## ${v.passed}/${v.checks} checks · ${v.probesRejecting}/${v.probes} probes rejecting — **${v.state}**

**A CHECK THAT CANNOT FAIL IS A SENTENCE.** Every check below is paired with an input that MUST make
it fail. The probe is not a second test of the same thing — it is a test of the DETECTOR. Three
defects in this package's own checks were found by a probe refusing to reject, and each is recorded
on the check it belongs to.

| check | what it asserts | result | the probe under it |
|---|---|---|---|
${v.results.map((r) => `| **${r.id}** | ${r.title} | ${r.pass ? 'PASS' : '**FAIL**'} | ${r.probe?.rejected ? 'rejected' : '**DID NOT REJECT**'} — ${r.probe?.name ?? '—'} |`).join('\n')}

## The detail

${v.results.map((r) => `### ${r.id} — ${r.title}

**${r.pass ? 'PASS' : 'FAIL'}.** Probe: *${r.probe?.name}* — ${r.probe?.rejected ? 'rejected' : 'DID NOT REJECT'}.

\`\`\`json
${JSON.stringify(r.detail, null, 2).slice(0, 2600)}
\`\`\`
`).join('\n')}`;
}

/* ------------------------------------------------------------------- the manifest ------- */
function walk(dir, out = []) {
  for (const e of readdirSync(join(PKG, dir), { withFileTypes: true })) {
    const rel = dir ? dir + '/' + e.name : e.name;
    if (e.isDirectory()) walk(rel, out);
    else out.push(rel);
  }
  return out;
}

function manifest() {
  const files = walk('').filter((f) => !f.endsWith('.zip')).sort();
  const rows = files.map((f) => {
    const b = readFileSync(join(PKG, f));
    return { path: f, bytes: b.length, sha256: createHash('sha256').update(b).digest('hex') };
  });
  const total = rows.reduce((a, r) => a + r.bytes, 0);
  const byTop = {};
  for (const r of rows) { const k = r.path.includes('/') ? r.path.split('/')[0] : '(root)'; byTop[k] = (byTop[k] ?? { n: 0, bytes: 0 }); byTop[k].n++; byTop[k].bytes += r.bytes; }
  return {
    json: { generatedBy: 'tools/f2-docs.mjs', files: rows.length, bytes: total, byDirectory: byTop, entries: rows },
    md: `# I-08B3.1-F2 — MANIFEST

**Generated by \`tools/f2-docs.mjs\`. Do not edit — edit the tool.**

**${rows.length} files · ${total.toLocaleString('en-US')} bytes.**

| directory | files | bytes |
|---|---:|---:|
${Object.entries(byTop).sort().map(([k, v]) => `| \`${k}\` | ${v.n} | ${v.bytes.toLocaleString('en-US')} |`).join('\n')}

**A NOTE ON REPRODUCIBILITY.** \`data/F2_MANIFEST.json\` hashes every file in the package including
\`docs/F2_MANIFEST.md\`, which is generated from it — so the manifest is a fixed point and its own
hash differs between two consecutive runs. The behaviour is inherited from I-08B3.1-F1 and is
stated rather than worked around: everything ELSE in the package is byte-stable across runs, and
\`tools/f2-consistency.mjs\` re-reads the shipped surfaces to prove it.

## Every file

| file | bytes | sha256 |
|---|---:|---|
${rows.map((r) => `| \`${r.path}\` | ${r.bytes.toLocaleString('en-US')} | \`${r.sha256.slice(0, 32)}\` |`).join('\n')}
`,
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(join(PKG, 'docs'), { recursive: true });
  writeFileSync(join(PKG, 'docs/F2_SKILL_GATE.md'), skillGate(), 'utf8');
  writeFileSync(join(PKG, 'docs/F2_REFERENCE_GATE.md'), referenceGate(), 'utf8');
  writeFileSync(join(PKG, 'docs/F2_VALIDATION_RESULTS.md'), validationResults(), 'utf8');
  const m = manifest();
  writeFileSync(join(PKG, 'data/F2_MANIFEST.json'), JSON.stringify(m.json, null, 2) + '\n', 'utf8');
  writeFileSync(join(PKG, 'docs/F2_MANIFEST.md'), m.md, 'utf8');
  console.log('generated: F2_SKILL_GATE.md, F2_REFERENCE_GATE.md, F2_VALIDATION_RESULTS.md, F2_MANIFEST.md');
  console.log('manifest:', m.json.files, 'files,', m.json.bytes.toLocaleString('en-US'), 'bytes');
}
