/**
 * I-08B3.1-A3 - manifest and packaging.
 *
 *   node tools/a3-package.mjs
 *
 * Writes docs/A3_MANIFEST.md (every file with its SHA-256) and then the zip.
 *
 * The zip is written by hand rather than with PowerShell's Compress-Archive, which emits entry
 * names separated by BACKSLASHES. The ZIP appendix requires forward slashes, so a
 * Compress-Archive archive extracts on macOS and Linux as files with literal backslashes in
 * their names instead of directories - and it looks perfectly fine on Windows, so the defect is
 * invisible from the machine that created it. A design review package opened on a Mac cannot
 * ship that way.
 *
 * The archive is verified by re-parsing the central directory of the file just written.
 * Scanning the raw buffer for 0x5C would be meaningless - deflate output contains that byte by
 * chance - so the entry names are read back properly instead.
 *
 * The archive is named from the PACKAGE DIRECTORY, never from a literal, so a later revision
 * cannot overwrite an earlier archive by inheriting a hard-coded name.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, basename } from 'node:path';
import { deflateRawSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { PKG } from './a3-ui.mjs';

const T = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c; }
  return t;
})();
const crc32 = (b) => { let c = -1; for (let i = 0; i < b.length; i++) c = T[(c ^ b[i]) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0; };

function walk(dir, out = []) {
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

const ROOT = basename(PKG);
const MANIFEST = join(PKG, 'docs', 'A3_MANIFEST.md');

/* ------------------------------------------------------------------ manifest --------- */
{
  // The manifest is added explicitly rather than taken from the walk: on a first run it does
  // not exist yet, and a manifest that omits itself would disagree with the archive's own file
  // count by exactly one - a discrepancy that looks like corruption.
  const files = walk(PKG).filter((p) => !p.endsWith('.zip'));
  if (!files.includes(MANIFEST)) files.push(MANIFEST);
  files.sort();
  const rows = files.map((abs) => {
    const rel = relative(PKG, abs).split(/[\\/]/).join('/');
    if (abs === MANIFEST) return { rel, bytes: '', sha: '(this file)' };
    const buf = readFileSync(abs);
    return { rel, bytes: buf.length, sha: createHash('sha256').update(buf).digest('hex') };
  });
  const group = (prefix) => rows.filter((r) => r.rel.startsWith(prefix));
  const table = (rs) => ['| File | Bytes | SHA-256 |', '|---|---|---|',
    ...rs.map((r) => `| \`${r.rel}\` | ${r.bytes} | \`${r.sha}\` |`)].join('\n');

  const md = `# I-08B3.1-A3R — MANIFEST

**I-08B3.1-A3R — CANONICAL-STATE CORRECTION COMPLETE / READY FOR FINAL DESIGN DIRECTOR FREEZE REVIEW / NOT FROZEN**

${rows.length} files. Generated by \`node tools/a3-package.mjs\`, which writes this file and
then builds the archive and verifies it by re-parsing its own central directory.

| | |
|---|---|
| **Revision** | A3R — one canonical-state contradiction corrected: QANDEEL is **DARK-LED, NOT DARK-LOCKED**, never "permanently dark". **No raster changed** (all 22 byte-identical), **no measurement changed**, **no colour value changed**. See \`A3R_REVISION_RECORD.md\` |
| **Original preserved** | The A3 package and archive are untouched at \`I-08B3.1-A3-WORLD-READING-NEUTRAL-CLOSURE-PROOF/\` and \`.zip\` |
| **Director decisions** | Recorded, not reinterpreted: World \`#101010\` selected; Primary **P1 \`#d8d5ca\`** selected and P2 retired as the Primary finalist; Secondary \`#afaca3\` remains; Tertiary \`#8b8982\` remains in the neutral system with its application rule routed to I-08B3.1-B and B3.1-F. **Not a winner produced by A3** |
| **What A3 decides** | **Nothing.** A3 closed the remaining perceptual uncertainty inside the selected thesis by producing evidence. The closure decision was the Design Director's |
| **Nothing is frozen** | \`#101010\` is the sole incumbent World Base and is **preserved, not confirmed**. P1 and P2 are candidates. The diagnostic Subtle, the diagnostic edge and the achromatic probe are **non-canonical scaffolding**. No Product colour is declared canonical |
| **The control** | \`#e1ded3\` is the A1 Primary, on the boards as a **reference only**. It is not a third finalist |
| **Retired** | Thesis B retired as challenger after A2R; thesis C remains retired. Neither exists in \`tools/a3-model.mjs\`, and the packager scans every text file for their values |
| **Evidence class** | Controlled browser renders under **two** raster conditions. No participants, no perceptual measurement, no native platform validation |
| **Skill Gate** | PASSED — \`A3_SKILL_GATE.md\`, 55 skills re-enumerated from disk across three scopes and checked against the A2R baseline |
| **Reference Gate** | PASSED — \`A3_REFERENCE_GATE.md\`, primary sources re-fetched; three changed since A2 and the changes are recorded |
| **Preflight** | PASSED — \`A3_PREFLIGHT.md\`, 12 checks, exits non-zero on failure |
| **Fairness** | PROVED — a candidate is ONE custom property; quiet 12 / map 39 / deep 15 / util 38 elements, identical, **in both raster conditions** |
| **Font** | Estedad v8.5 referenced, **binary not redistributed**; identity, hash and licence only |

## Boards

${table(group('review/'))}

## Documents

${table(group('docs/'))}

## Tools

${table(group('tools/'))}

## Font information

${table(group('fonts-info/'))}
`;
  writeFileSync(MANIFEST, md, 'utf8');
  console.log(`A3_MANIFEST.md  ${rows.length} files listed`);
}

/* ---------------------------------------------------------------------- zip ---------- */
const files = walk(PKG).filter((p) => !p.endsWith('.zip'));
const dosTime = (d) => ((d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1)) & 0xffff;
const dosDate = (d) => (((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate()) & 0xffff;
const now = new Date();

const local = [], central = [];
let offset = 0;

for (const abs of files) {
  const name = `${ROOT}/${relative(PKG, abs).split(/[\\/]/).join('/')}`;   // forward slashes, always
  const nameBuf = Buffer.from(name, 'utf8');
  const data = readFileSync(abs);
  const comp = deflateRawSync(data, { level: 9 });
  const useStore = comp.length >= data.length;
  const body = useStore ? data : comp;
  const method = useStore ? 0 : 8;
  const crc = crc32(data);

  const lh = Buffer.alloc(30);
  lh.writeUInt32LE(0x04034b50, 0);
  lh.writeUInt16LE(20, 4);
  lh.writeUInt16LE(0x0800, 6);            // UTF-8 name flag
  lh.writeUInt16LE(method, 8);
  lh.writeUInt16LE(dosTime(now), 10);
  lh.writeUInt16LE(dosDate(now), 12);
  lh.writeUInt32LE(crc, 14);
  lh.writeUInt32LE(body.length, 18);
  lh.writeUInt32LE(data.length, 22);
  lh.writeUInt16LE(nameBuf.length, 26);
  lh.writeUInt16LE(0, 28);
  local.push(lh, nameBuf, body);

  const ch = Buffer.alloc(46);
  ch.writeUInt32LE(0x02014b50, 0);
  ch.writeUInt16LE(0x031e, 4);            // made by: UNIX, zip 3.0
  ch.writeUInt16LE(20, 6);
  ch.writeUInt16LE(0x0800, 8);
  ch.writeUInt16LE(method, 10);
  ch.writeUInt16LE(dosTime(now), 12);
  ch.writeUInt16LE(dosDate(now), 14);
  ch.writeUInt32LE(crc, 16);
  ch.writeUInt32LE(body.length, 20);
  ch.writeUInt32LE(data.length, 24);
  ch.writeUInt16LE(nameBuf.length, 28);
  for (const off of [30, 32, 34, 36]) ch.writeUInt16LE(0, off);
  // (0o100644 << 16) overflows a signed 32-bit int; coerce before writing.
  ch.writeUInt32LE((0o100644 << 16) >>> 0, 38);
  ch.writeUInt32LE(offset, 42);
  central.push(ch, nameBuf);

  offset += lh.length + nameBuf.length + body.length;
}

const cdBuf = Buffer.concat(central);
const eocd = Buffer.alloc(22);
eocd.writeUInt32LE(0x06054b50, 0);
eocd.writeUInt16LE(0, 4);
eocd.writeUInt16LE(0, 6);
eocd.writeUInt16LE(files.length, 8);
eocd.writeUInt16LE(files.length, 10);
eocd.writeUInt32LE(cdBuf.length, 12);
eocd.writeUInt32LE(offset, 16);
eocd.writeUInt16LE(0, 20);

const out = join(PKG, '..', `${ROOT}.zip`);
writeFileSync(out, Buffer.concat([...local, cdBuf, eocd]));

/* ---- verify by re-parsing the central directory of the file just written -------------- */
const check = readFileSync(out);
const eocdAt = check.length - 22;
const nEntries = check.readUInt16LE(eocdAt + 10);
let p = check.readUInt32LE(eocdAt + 16), backslashes = 0, dirEntries = 0;
const names = [];
for (let i = 0; i < nEntries; i++) {
  if (check.readUInt32LE(p) !== 0x02014b50) throw new Error('central directory corrupt');
  const nl = check.readUInt16LE(p + 28), el = check.readUInt16LE(p + 30), cl = check.readUInt16LE(p + 32);
  const nm = check.toString('utf8', p + 46, p + 46 + nl);
  names.push(nm);
  if (nm.includes('\\')) backslashes++;
  if (nm.endsWith('/')) dirEntries++;
  p += 46 + nl + el + cl;
}

console.log(`${files.length} files -> ${out}`);
console.log(`${(check.length / 1024 / 1024).toFixed(2)} MB`);
console.log(`central directory entries : ${nEntries} (matches file count: ${nEntries === files.length})`);
console.log(`entry names with backslash: ${backslashes}  ${backslashes === 0 ? '(ok)' : '(BROKEN on macOS/Linux)'}`);
console.log(`directory entries         : ${dirEntries} (files only, as intended)`);

/* The deliverable is the named board set. Ship without one and the package is not the package,
   so it is checked here rather than trusted to have happened earlier. */
const REQUIRED_BOARDS = [
  'READING_01_ROLE_MATRIX', 'READING_02_LONG_FORM', 'BLIND_READING_X_Y',
  'HIERARCHY_RAMP', 'HEADROOM_P1_P2', 'METADATA_TRUE_SIZE', 'METADATA_MAGNIFIED',
  'ENV_P1_1_QUIET', 'ENV_P1_2_MAP', 'ENV_P1_3_DEEP', 'ENV_P1_4_UTIL',
  'ENV_P2_1_QUIET', 'ENV_P2_2_MAP', 'ENV_P2_3_DEEP', 'ENV_P2_4_UTIL',
  'ROBUSTNESS_MOBILE_P1', 'ROBUSTNESS_MOBILE_P2', 'ROBUSTNESS_MOBILE_PAIR',
  'ROBUSTNESS_METADATA_4X',
];
const REQUIRED_FAILURES = [
  'FAILURE_TERTIARY_BELOW_APPLE_7TO1', 'FAILURE_METADATA_400_IN_PRODUCT',
  'CONTROL_COLLAPSED_HIERARCHY',
];
const REQUIRED_DOCS = [
  'A3_README', 'A3_METHOD', 'A3_PREFLIGHT', 'A3_SKILL_GATE', 'A3_REFERENCE_GATE',
  'A3_FINDINGS', 'A3_FAILURES', 'A3_MANIFEST', 'A3R_REVISION_RECORD',
];
const missing = [
  ...REQUIRED_BOARDS.filter((r) => !names.includes(`${ROOT}/review/${r}.png`)),
  ...REQUIRED_FAILURES.filter((r) => !names.includes(`${ROOT}/review/failures/${r}.png`)),
  ...REQUIRED_DOCS.filter((r) => !names.includes(`${ROOT}/docs/${r}.md`)),
  ...['A3_MEASUREMENTS.csv', 'A3_MEASUREMENTS.json'].filter((r) => !names.includes(`${ROOT}/docs/${r}`)),
];
const extraBoards = names.filter((n) => n.startsWith(`${ROOT}/review/`) && n.endsWith('.png'))
  .filter((n) => ![...REQUIRED_BOARDS.map((r) => `${ROOT}/review/${r}.png`),
                   ...REQUIRED_FAILURES.map((r) => `${ROOT}/review/failures/${r}.png`)].includes(n));

/* Thesis B is retired as challenger and thesis C remains retired. A file that carried one of
   their values would be a contract breach, so the package is searched for their A1 hexes rather
   than trusted not to contain them.
   Three files are excluded, and the reason is the same one the preflight gives: this file and
   `a3-preflight.mjs` both DEFINE the needles, and a scanner that reports itself fails every run
   and teaches nothing; `A3_PREFLIGHT.md` is the preflight's OWN OUTPUT, which prints the
   offending values when a run fails - scanning it would let one real failure poison every later
   run and make its origin untraceable. */
const RETIRED_HEXES = [
  '#101415', '#161a1b', '#e0e3e5', '#afb1b2', '#8c8e8f',   // thesis B
  '#191511', '#120f0b', '#dfdcd8', '#aeaca9', '#8a8885',   // thesis C
];
const NEEDLE_FILES = ['a3-package.mjs', 'a3-preflight.mjs', 'A3_PREFLIGHT.md'];
const textFiles = files.filter((p) => /\.(md|mjs|csv|json|txt)$/.test(p) && !NEEDLE_FILES.includes(basename(p)));
const leak = [];
for (const p of textFiles) {
  const t = readFileSync(p, 'utf8').toLowerCase();
  for (const h of RETIRED_HEXES) if (t.includes(h)) leak.push(`${relative(PKG, p)} contains ${h}`);
}

console.log(`required artefacts present: ${missing.length === 0 ? 'all' : 'MISSING ' + missing.join(', ')}`);
console.log(`unexpected boards         : ${extraBoards.length}${extraBoards.length ? ' - ' + extraBoards.join(', ') : ' (review/ holds exactly the named set)'}`);
console.log(`retired thesis B/C values : ${leak.length === 0 ? 'absent (ok)' : 'PRESENT - ' + leak.join('; ')}`);

const sha = createHash('sha256').update(check).digest('hex').toUpperCase();
console.log(`\nSHA-256 ${sha}`);
console.log(`bytes   ${check.length}`);

if (backslashes || nEntries !== files.length || missing.length || extraBoards.length || leak.length) process.exit(1);
